/**
 * Grounded product help — Exchange Assistant capability, not a workflow.
 */

export function productHelpAnswer(goal: string | null, message: string): string {
  const g = `${goal ?? ""} ${message}`.toLowerCase();
  if (/טמפלייט|תבנית|פורמט|כמה רכבים|ביחד/.test(g)) {
    return `אפשר לשלוח כמה רכבים בהודעה אחת — שורה לכל רכב, למשל:
טויוטה קורולה | 2022 | 62 אלף ק"מ | יד 1 | 134 אלף לסוחר
מאזדה 3 | 2021 | 75 אלף | יד 2 | 92 לסוחר`;
  }
  if (/מחיר לסוחר|b2b/.test(g)) {
    return "מחיר לסוחר הוא המחיר בין סוחרים ב-Exchange — לא מחיר ללקוח קצה. הוא נדרש להתאמה מסחרית, בלי לחשוף גמישות או זהות.";
  }
  if (/התאמ/.test(g) && /איך|למה|עובד/.test(g)) {
    return "התאמות נקבעות לפי כללי המערכת (אילוצים קשיחים וציון), לא לפי ניחוש. מוצגות רק התאמות מאושרות שלך. זהות הסוחר נחשפת רק אחרי עניין הדדי.";
  }
  if (/מי הסוחר|חשיפ|reveal/.test(g)) {
    return "לא מציגים זהות סוחר לפני עניין הדדי. אחרי חיבור — החשיפה במסך החיבורים, עם פרטי קשר מאושרים בלבד.";
  }
  if (/פרטי מודעה|חשוב|לכתוב/.test(g)) {
    return "למודעה שימושית: יצרן, דגם, שנה, קילומטראז׳ ומחיר לסוחר. השאר אפשר להשלים אחר כך.";
  }
  if (/תקציב/.test(g)) {
    return "תקציב מקסימלי בחיפוש הוא תקרת מחיר לסוחר שאתה מוכן לשקול. חריגה קלה מטופלת בכללי המערכת — בלי לחשוף כמה תשלם באמת.";
  }
  return "אפשר לשאול על מלאי, חיפושים, התאמות, חשיפות או מה דורש טיפול — ואני עונה מתוך הנתונים המאושרים שלך בלבד.";
}
